(() => {
  "use strict";

  const form = document.getElementById("app-guide-form");
  if (!form) return;

  const steps = Array.from(form.querySelectorAll("[data-app-guide-step]"));
  const progress = document.getElementById("app-guide-progress");
  const back = document.getElementById("app-guide-back");
  const next = document.getElementById("app-guide-next");
  const error = document.getElementById("app-guide-error");
  const result = document.getElementById("app-guide-result");
  const recommendation = document.getElementById("app-guide-recommendation");
  const labels = {
    maintainer: { business: "Business user", maker: "Power Platform maker", developer: "Developer" },
    surface: { standalone: "Standalone app", "model-driven": "Existing model-driven app", copilot: "Microsoft 365 Copilot chat" },
    needs: { prototype: "Prototype", team: "Team app", enterprise: "Complex enterprise app" }
  };
  const stepNames = ["Maintainer", "Surface", "Lifespan and needs"];
  let step = 0;

  function choosePath({ maintainer, surface, needs }) {
    if (surface === "model-driven") {
      return {
        title: "Start with standard forms and views",
        why: "People already work in a model-driven app. Extend it with standard forms and views first. Consider a generative page if the task needs a more custom experience.",
        owner: "Work with a model-driven app maker who can change the configuration and pages. Agree who will review generated content and support the app.",
        check: "Check Dataverse permissions, page behavior, accessibility, supported features, and how you'll deploy changes to the existing app.",
        href: "https://aka.ms/genpages-docs",
        link: "Read the generative pages documentation"
      };
    }
    if (surface === "copilot") {
      return {
        title: "Explore Copilot integration for a model-driven app",
        why: "You want people to use the app's data and actions in Microsoft 365 Copilot chat. The deck describes a model-driven app integration using MCP.",
        owner: "You'll need an app owner and an integration owner to maintain the data, actions, permissions, and connection.",
        check: "This path comes from the November 2026 deck. Check current Microsoft documentation for Copilot integration, MCP setup, tenant requirements, authentication, and licensing. If you don't have a model-driven app, check the data and integration approach first.",
        href: "techcon365-dallas-mcp.html",
        link: "Read the companion MCP session guide"
      };
    }
    if (maintainer === "business" && needs === "prototype") {
      return {
        title: "Explore prompt-to-app in Copilot Studio or Cowork",
        why: "A prototype lets you test the idea before choosing how you'll build and maintain the final app.",
        owner: "Decide who will edit and support it, and check that they can use its editing tools. Don't assume the generated app opens as a canvas app in Studio.",
        check: "Check current availability, preview status, runtime, user access, licensing, and editing limits. The November 2026 deck distinguishes Copilot Managed Runtime from Power Platform governance. Review data access and security even for a prototype.",
        href: "https://learn.microsoft.com/microsoft-copilot-studio/apps-experience/apps-overview",
        link: "Read the Apps in Copilot Studio documentation"
      };
    }
    if (maintainer === "developer" && needs === "enterprise") {
      return {
        title: "Consider a developer-owned code app",
        why: "A developer-maintained app may need custom code and UI. Check whether a standard model-driven app would do the job before taking on that extra work.",
        owner: "The development team handles source control, reviews, dependencies, tests, debugging, deployment, and long-term maintenance, including any code generated by AI.",
        check: "Check supported code-app features, integrations, authentication, licensing, accessibility, monitoring, and release management. Test the app before using it in production.",
        href: "https://aka.ms/codeapps-docs",
        link: "Read the code apps documentation"
      };
    }
    return {
      title: "Compare a canvas app with a model-driven app",
      why: "The choice depends on the UI and data. A canvas app gives you a custom layout, forms, or mobile experience. A model-driven app starts with Dataverse data, roles, rules, forms, and views.",
      owner: maintainer === "business"
        ? "Work with a Power Platform maker who can handle future changes and support. Try the handoff before choosing the tool."
        : maintainer === "developer"
          ? "Name someone to own configuration and changes in the maker tools, even if developers or coding agents help build the app. You may not need custom code."
          : "A Power Platform maker handles the app, its data model, changes, tests, and support. Check that they can maintain the result when using AI to help build it.",
      check: "Check data sources, permissions, UI needs, accessibility, licensing, environments, and release management. Try one real task in each approach before deciding.",
      href: "#match-the-path",
      link: "Read the written app-path comparison"
    };
  }

  function clearError() {
    error.hidden = true;
    error.textContent = "";
    steps.forEach((fieldset) => {
      fieldset.removeAttribute("aria-describedby");
      fieldset.removeAttribute("aria-invalid");
    });
  }

  function showStep(moveFocus) {
    clearError();
    result.hidden = true;
    recommendation.textContent = "";
    steps.forEach((fieldset, index) => {
      fieldset.hidden = index !== step;
      fieldset.disabled = index !== step;
    });
    progress.textContent = `Step ${step + 1} of 3: ${stepNames[step]}`;
    back.disabled = step === 0;
    next.hidden = false;
    next.textContent = step === 2 ? "Show my starting path" : "Next question";
    if (moveFocus) steps[step].querySelector("legend").focus();
  }

  function showResult(moveFocus = true) {
    const answers = {};
    for (const fieldset of steps) {
      const selected = fieldset.querySelector("input:checked");
      if (!selected) {
        step = steps.indexOf(fieldset);
        showStep(true);
        return;
      }
      answers[selected.name] = selected.value;
    }
    const path = choosePath(answers);
    document.getElementById("app-guide-selection").textContent =
      `Your choices: ${labels.maintainer[answers.maintainer]} · ${labels.surface[answers.surface]} · ${labels.needs[answers.needs]}.`;
    document.getElementById("app-guide-why").textContent = path.why;
    document.getElementById("app-guide-owner").textContent = path.owner;
    const planningCheck = {
      prototype: "Use appropriate test data for the prototype, and agree what needs to happen before wider use.",
      team: "For a team app, plan shared access, support, testing, and cover when the owner is away.",
      enterprise: "For an enterprise app, test integrations, scale, recovery, and the release process, and arrange ongoing support."
    };
    document.getElementById("app-guide-check").textContent =
      `${path.check} ${planningCheck[answers.needs]} Whichever path you choose, confirm where the app runs, which data policies apply, how admins track it, how it's billed, and who owns it.`;
    const reference = document.getElementById("app-guide-reference");
    reference.href = path.href;
    reference.textContent = path.link;
    steps.forEach((fieldset) => {
      fieldset.hidden = true;
      fieldset.disabled = true;
    });
    progress.textContent = "Complete: Your starting path";
    next.hidden = true;
    back.disabled = false;
    result.hidden = false;
    recommendation.textContent = path.title;
    if (moveFocus) document.getElementById("app-guide-result-heading").focus();
  }

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    clearError();
    const selected = steps[step].querySelector("input:checked");
    if (!selected) {
      error.textContent = "Choose one option to continue.";
      error.hidden = false;
      steps[step].setAttribute("aria-describedby", error.id);
      steps[step].setAttribute("aria-invalid", "true");
      steps[step].querySelector("input").focus();
      return;
    }
    if (step < steps.length - 1) {
      step += 1;
      showStep(true);
    } else {
      showResult();
    }
  });
  form.addEventListener("change", clearError);
  back.addEventListener("click", () => {
    if (result.hidden) step = Math.max(0, step - 1);
    showStep(true);
  });
  document.getElementById("app-guide-reset").addEventListener("click", () => {
    form.reset();
    step = 0;
    showStep(true);
  });

  // Keep the visible step in sync with restored radio values on back/forward navigation.
  window.addEventListener("pageshow", (event) => {
    if (event.persisted) {
      if (result.hidden) showStep(false);
      else showResult(false);
    }
  });
  form.noValidate = true;
  showStep(false);
  form.hidden = false;
})();
